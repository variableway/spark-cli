type summary struct {
	Suites        int
	Specs         int
	Passed        int
	Failed        int
	Skipped       int
	Pending       int
	Other         int
	Duration      string
	Succeeded     bool
	GeneratedText string
}

type specRow struct {
	Suite       string
	Description string
	State       string
	Class       string
	Duration    string
	Location    string
	Message     string
	Output      string
}

type suiteRow struct {
	Description string
	State       string
	Class       string
	Specs       int
	Duration    string
	Message     string
}

type view struct {
	Summary summary
	Suites  []suiteRow
	Specs   []specRow
}

func isFailedState(s types.SpecState) bool {
	switch s {
	case types.SpecStateFailed, types.SpecStatePanicked, types.SpecStateInterrupted,
		types.SpecStateAborted, types.SpecStateTimedout:
		return true
	default:
		return false
	}
}

func stateClass(s types.SpecState) string {
	switch {
	case s == types.SpecStatePassed:
		return "passed"
	case isFailedState(s):
		return "failed"
	case s == types.SpecStateSkipped:
		return "skipped"
	case s == types.SpecStatePending:
		return "pending"
	default:
		return "other"
	}
}

func specDescription(r types.SpecReport) string {
	parts := append([]string{}, r.ContainerHierarchyTexts...)
	if r.LeafNodeText != "" {
		parts = append(parts, r.LeafNodeText)
	}
	return strings.Join(parts, " ")
}

func summarize(reports []types.Report) view {
	v := view{Summary: summary{Suites: len(reports), Succeeded: true}}

	var total int64
	for _, r := range reports {
		if !r.SuiteSucceeded {
			v.Summary.Succeeded = false
		}
		total += int64(r.RunTime)

		s := suiteRow{
			Description: r.SuiteDescription,
			Specs:       len(r.SpecReports),
			Duration:    fmtDuration(int64(r.RunTime)),
			Message:     strings.Join(r.SpecialSuiteFailureReasons, "\n"),
		}
		if r.SuiteSucceeded {
			s.State, s.Class = "PASSED", "passed"
		} else {
			s.State, s.Class = "FAILED", "failed"
		}
		v.Suites = append(v.Suites, s)

		for _, sr := range r.SpecReports {
			row := specRow{
				Suite:       r.SuiteDescription,
				Description: specDescription(sr),
				State:       sr.State.String(),
				Class:       stateClass(sr.State),
				Duration:    fmtDuration(int64(sr.RunTime)),
				Location:    sr.LeafNodeLocation.String(),
				Message:     sr.Failure.Message,
				Output:      sr.CapturedStdOutErr,
			}
			if row.Description == "" {
				row.Description = "(suite node)"
			}
			v.Specs = append(v.Specs, row)

			switch {
			case sr.State == types.SpecStatePassed:
				v.Summary.Passed++
			case isFailedState(sr.State):
				v.Summary.Failed++
			case sr.State == types.SpecStateSkipped:
				v.Summary.Skipped++
			case sr.State == types.SpecStatePending:
				v.Summary.Pending++
			default:
				v.Summary.Other++
			}
		}
		v.Summary.Specs += len(r.SpecReports)
	}

	v.Summary.Duration = fmtDuration(total)
	v.Summary.GeneratedText = "Generated by spark testreport"
	return v
}

// Render converts Ginkgo reports into a self-contained HTML document that
// lists every suite and spec with its state, duration and failure details.
func Render(reports []types.Report) (string, error) {
	v := summarize(reports)

	var buf bytes.Buffer
	if err := pageTemplate.Execute(&buf, v); err != nil {
		return "", fmt.Errorf("render template: %w", err)
	}
	return buf.String(), nil
}

func fmtDuration(ns int64) string {
	d := ns / 1000 / 1000
	if d < 1000 {
		return fmt.Sprintf("%dms", d)
	}
	return fmt.Sprintf("%.2fs", float64(d)/1000)
}

// WriteFile renders the reports and writes the HTML document to dest,
// creating parent directories as needed.
func WriteFile(reports []types.Report, dest string) error {
	html, err := Render(reports)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0755); err != nil {
		return err
	}
	return os.WriteFile(dest, []byte(html), 0644)
}

